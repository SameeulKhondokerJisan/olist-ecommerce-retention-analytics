"""End-to-end pipeline: warehouse -> analysis -> CLV -> figures -> Excel, Power BI, docs.

Usage:
    python -m src.run_pipeline                  # full run
    python -m src.run_pipeline --analysis-only  # skip Excel, Power BI and README rendering
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone

import numpy as np
import pandas as pd

from src import analysis, clv, config, data, figures


def records(df: pd.DataFrame) -> list[dict]:
    out = []
    for rec in df.to_dict(orient="records"):
        clean = {}
        for k, v in rec.items():
            if isinstance(v, (pd.Timestamp, datetime)):
                clean[k] = v.strftime("%Y-%m-%d")
            elif isinstance(v, (np.floating, float)):
                clean[k] = None if np.isnan(v) else float(v)
            elif isinstance(v, np.integer):
                clean[k] = int(v)
            elif isinstance(v, np.bool_):
                clean[k] = bool(v)
            else:
                clean[k] = v
        out.append(clean)
    return out


def write_quality_log(checks: pd.DataFrame, counts: dict) -> None:
    lines = ["# Data quality log", "",
             "Generated by `src/run_pipeline.py` from `sql/03_quality_checks.sql`. Hard rules stop the pipeline; "
             "soft rules are handled as described in `sql/02_staging.sql` and recorded here.", "",
             "| Rule | Severity | Rows | Status |", "|---|---|---:|---|"]
    for r in checks.itertuples():
        status = "pass" if r.failures == 0 else ("FAIL" if r.severity == "hard" else "handled")
        lines.append(f"| {r.rule} | {r.severity} | {int(r.failures):,} | {status} |")
    lines += ["", "## Row counts", "", "| Table | Rows |", "|---|---:|"]
    lines += [f"| {k} | {v:,} |" for k, v in counts.items()]
    (config.ROOT / "docs" / "data_quality_log.md").write_text("\n".join(lines) + "\n")


def run_clv(orders: pd.DataFrame) -> tuple[dict, pd.DataFrame]:
    cal_end = pd.Timestamp(f"{config.CALIBRATION_END} 23:59:59")
    check = clv.holdout_check(orders, cal_end, config.HOLDOUT_WEEKS)
    end = pd.Timestamp(f"{config.CUTOFF} 23:59:59")
    summary = clv.rfm_summary(orders, end)
    bg = clv.BGNBD().fit(summary)
    rep = summary[summary.x > 0]
    gg = clv.GammaGamma().fit(rep.x + 1, rep.monetary)   # m is the mean over x+1 purchase days
    summary["exp_purchases_52w"] = bg.expected_purchases(52, summary.x, summary.t_x, summary["T"])
    summary["prob_alive"] = bg.prob_alive(summary.x, summary.t_x, summary["T"])
    summary["exp_value_per_purchase"] = gg.expected_avg_value(np.where(summary.x > 0, summary.x + 1, 0),
                                                              summary.monetary)
    summary["clv_12m_gmv"] = summary.exp_purchases_52w * summary.exp_value_per_purchase
    info = {"holdout": {k: v for k, v in check.items() if k != "by_frequency"},
            "holdout_by_frequency": records(check["by_frequency"]),
            "bgnbd": {"r": bg.r, "alpha": bg.alpha, "a": bg.a, "b": bg.b},
            "gamma_gamma": {"p": gg.p, "q": gg.q, "v": gg.v},
            "customers_scored": int(len(summary)),
            "expected_repeat_purchases_52w": float(summary.exp_purchases_52w.sum()),
            "expected_repeat_gmv_52w": float(summary.clv_12m_gmv.sum()),
            "mean_clv_12m_gmv": float(summary.clv_12m_gmv.mean())}
    return info, summary.reset_index().rename(columns={"index": "customer_unique_id"}), check["by_frequency"]


def main(analysis_only: bool = False) -> dict:
    for folder in (config.FIGURES, config.TABLES, config.POWERBI_DATA):
        folder.mkdir(parents=True, exist_ok=True)
    checks = data.build_warehouse()
    counts = data.row_counts()
    write_quality_log(checks, counts)

    orders = data.table("fact_orders")
    orders["purchase_ts"] = pd.to_datetime(orders.purchase_ts)
    orders["purchase_month"] = pd.to_datetime(orders.purchase_month)
    cohorts = data.query("05_cohort_retention.sql")
    states = data.query("06_delivery_kpis.sql")
    sellers = data.query("07_seller_scorecard.sql")
    monthly = data.query("08_monthly_kpis.sql")
    monthly["purchase_month"] = pd.to_datetime(monthly.purchase_month)

    rfm = analysis.rfm_table(orders)
    rfm["cluster"], k_scores = analysis.kmeans_segments(rfm)
    seg = (rfm.groupby("segment").agg(customers=("frequency", "size"), gmv=("monetary", "sum"),
                                      avg_recency_days=("recency_days", "mean"), avg_orders=("frequency", "mean"))
           .reset_index())
    seg["gmv_share"] = seg.gmv / seg.gmv.sum()
    clusters = (rfm.groupby("cluster").agg(customers=("frequency", "size"), avg_recency_days=("recency_days", "mean"),
                                           avg_orders=("frequency", "mean"), avg_monetary=("monetary", "mean"))
                .reset_index())

    d = analysis.delivered_reviewed(orders)
    review_stats = analysis.review_by_lateness(d)
    buckets = analysis.review_by_delay_bucket(d)
    ordinal = analysis.ordinal_model(d)
    first = analysis.first_orders(orders)
    repeat = analysis.repeat_by_first_delivery(first)
    clv_info, clv_scores, holdout_freq = run_clv(orders)

    last12 = orders[orders.purchase_ts > pd.Timestamp(config.CUTOFF) - pd.DateOffset(months=12)]
    business = {
        "orders": int(len(orders)), "customers": int(orders.customer_unique_id.nunique()),
        "gmv": float(orders.order_value.sum()), "avg_order_value": float(orders.order_value.mean()),
        "first_month": orders.purchase_month.min().strftime("%Y-%m"), "last_month": orders.purchase_month.max().strftime("%Y-%m"),
        "customers_last_12m": int(last12.customer_unique_id.nunique()),
        "orders_last_12m": int(len(last12)),
        "gmv_last_12m": float(last12.order_value.sum()),
        "avg_order_value_last_12m": float(last12.order_value.mean()),
        "share_customers_one_order": float((rfm.frequency == 1).mean()),
        "late_rate_delivered": float(orders.loc[orders.is_delivered, "is_late"].astype(float).mean()),
        "avg_review": float(orders.review_score.mean()),
        "month1_retention_avg": float(cohorts[cohorts.months_since_first == 1].retention_rate.mean()),
    }

    tables = {"quality_checks": checks, "cohort_retention": cohorts, "delivery_by_state": states,
              "seller_scorecard": sellers, "monthly_kpis": monthly, "rfm_segments": seg,
              "kmeans_clusters": clusters, "kmeans_k_selection": k_scores, "review_by_delay_bucket": buckets,
              "clv_holdout_by_frequency": holdout_freq}
    for name, t in tables.items():
        t.to_csv(config.TABLES / f"{name}.csv", index=False)
    clv_scores.sort_values("clv_12m_gmv", ascending=False).head(1000).to_csv(
        config.TABLES / "top_1000_customers_by_clv.csv", index=False)

    figs = [figures.monthly_kpis(monthly), figures.cohort_heatmap(cohorts), figures.review_by_delay(buckets),
            figures.late_rate_by_state(states), figures.segment_sizes(seg), figures.clv_holdout(holdout_freq)]

    results = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "settings": {"cutoff": config.CUTOFF, "calibration_end": config.CALIBRATION_END,
                     "holdout_weeks": config.HOLDOUT_WEEKS, "repeat_window_days": config.REPEAT_WINDOW_DAYS,
                     "currency": config.CURRENCY},
        "assumptions": {"contribution_margin": config.CONTRIBUTION_MARGIN, "target_review": config.TARGET_REVIEW,
                        "voucher_cost": config.VOUCHER_COST},
        "row_counts": counts,
        "quality": {"hard_checks_passed": True, "soft_findings": records(checks[(checks.severity == "soft")
                                                                                 & (checks.failures > 0)])},
        "business": business, "review_vs_lateness": review_stats, "review_by_delay_bucket": records(buckets),
        "ordinal_model": ordinal, "repeat_vs_first_delivery": repeat, "clv": clv_info,
        "rfm_segments": records(seg), "kmeans": {"k_selection": records(k_scores), "clusters": records(clusters)},
        "worst_states_late_rate": records(states[states.delivered_orders >= 1000].sort_values(
            "late_rate", ascending=False).head(5)),
        "figures": figs,
    }
    config.RESULTS_JSON.write_text(json.dumps(results, indent=2, default=str))

    if not analysis_only:
        from src import excel_model, powerbi, report
        powerbi.export(orders, rfm, clv_scores, cohorts, states)
        excel_model.build(results)
        report.render(results)
    print(f"Pipeline finished: {business['orders']:,} orders, {business['customers']:,} customers")
    return results


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--analysis-only", action="store_true")
    main(analysis_only=parser.parse_args().analysis_only)
